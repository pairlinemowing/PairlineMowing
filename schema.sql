-- Pairline Mowing owner dashboard database setup.
-- Replace the email in the policies with the exact Google account email used by the owner.
-- NEVER put a service_role key in the website.

create table if not exists public.site_settings (
  id bigint primary key,
  google_review_url text not null default 'https://www.google.com/search?q=Pairline+Mowing+Port+Huron+MI',
  service_area_text text not null default 'Pairline Mowing serves Port Huron, Michigan and surrounding areas. Contact us to ask whether your address is within our service area.'
);

create table if not exists public.services (
  id bigint generated by default as identity primary key,
  name text not null,
  description text not null,
  sort_order integer not null default 1,
  published boolean not null default true
);

create table if not exists public.gallery (
  id bigint generated by default as identity primary key,
  image_url text not null,
  caption text not null default '',
  sort_order integer not null default 1,
  published boolean not null default true
);

create table if not exists public.reviews (
  id bigint generated by default as identity primary key,
  name text not null,
  title text not null default '',
  text text not null,
  sort_order integer not null default 1,
  published boolean not null default true
);

alter table public.site_settings enable row level security;
alter table public.services enable row level security;
alter table public.gallery enable row level security;
alter table public.reviews enable row level security;

drop policy if exists "public read settings" on public.site_settings;
drop policy if exists "owner write settings" on public.site_settings;
drop policy if exists "public read services" on public.services;
drop policy if exists "owner write services" on public.services;
drop policy if exists "public read gallery" on public.gallery;
drop policy if exists "owner write gallery" on public.gallery;
drop policy if exists "public read reviews" on public.reviews;
drop policy if exists "owner write reviews" on public.reviews;

create policy "public read settings" on public.site_settings for select using (true);
create policy "owner write settings" on public.site_settings for all using (lower(coalesce(auth.jwt()->>'email','')) = lower('REPLACE_WITH_OWNER_GOOGLE_EMAIL')) with check (lower(coalesce(auth.jwt()->>'email','')) = lower('REPLACE_WITH_OWNER_GOOGLE_EMAIL'));

create policy "public read services" on public.services for select using (published = true);
create policy "owner write services" on public.services for all using (lower(coalesce(auth.jwt()->>'email','')) = lower('REPLACE_WITH_OWNER_GOOGLE_EMAIL')) with check (lower(coalesce(auth.jwt()->>'email','')) = lower('REPLACE_WITH_OWNER_GOOGLE_EMAIL'));

