-- Storage bucket for owner-uploaded project photos.
insert into storage.buckets (id,name,public) values ('site-images','site-images',true) on conflict (id) do update set public = true;

drop policy if exists "public view site images" on storage.objects;
drop policy if exists "owner upload site images" on storage.objects;
drop policy if exists "owner update site images" on storage.objects;
drop policy if exists "owner delete site images" on storage.objects;
create policy "public view site images" on storage.objects for select using (bucket_id = 'site-images');
create policy "owner upload site images" on storage.objects for insert with check (bucket_id = 'site-images' and lower(coalesce(auth.jwt()->>'email','')) = lower('REPLACE_WITH_OWNER_GOOGLE_EMAIL'));
create policy "owner update site images" on storage.objects for update using (bucket_id = 'site-images' and lower(coalesce(auth.jwt()->>'email','')) = lower('REPLACE_WITH_OWNER_GOOGLE_EMAIL')) with check (bucket_id = 'site-images' and lower(coalesce(auth.jwt()->>'email','')) = lower('REPLACE_WITH_OWNER_GOOGLE_EMAIL'));
